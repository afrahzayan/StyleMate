/**
 * Finds the closest matching pre-defined combination prompt, or generates a dynamic fallback description.
 */
export function getCombinationDetails(selections = {}) {
  const targetType = selections.clothingType || "Shirt";

  // Check exact match
  const exact = FINAL_COMBINATIONS.find(
    (c) =>
      c.clothingType.toLowerCase() === targetType.toLowerCase() &&
      (!selections.color || c.color.toLowerCase().includes(selections.color.toLowerCase())) &&
      (!selections.fabric || c.fabric.toLowerCase() === selections.fabric.toLowerCase())
  );

  if (exact) return exact;

  // Build dynamic prompt for custom combination
  const colorStr = selections.color || "Classic";
  const fabricStr = selections.fabric || "Premium Fabric";
  const sleeveStr = selections.sleeveType ? `${selections.sleeveType} sleeves` : "tailored sleeves";
  const neckStr = selections.neckType ? `${selections.neckType} neckline` : "neckline";
  const lengthStr = selections.length ? `${selections.length} length` : "length";
  const patternStr = selections.pattern && selections.pattern !== "Plain" ? `${selections.pattern} pattern` : "plain fabric";
  const stoneStr = selections.stoneWork && selections.stoneWork !== "None" ? `${selections.stoneWork.toLowerCase()} stone work` : "no stone work";

  const dynamicDesc = `Create a 1500×1500 transparent PNG of a ${colorStr.toLowerCase()} ${fabricStr.toLowerCase()} ${targetType.toLowerCase()} with ${sleeveStr}, ${neckStr}, ${lengthStr}, ${patternStr}, and ${stoneStr}. Rendered on the standard front-facing mannequin, clean studio clothing visual, transparent background.`;

  return {
    id: `custom-${targetType.toLowerCase()}`,
    clothingType: targetType,
    color: selections.color || "Standard",
    fabric: selections.fabric || "Cotton",
    sleeveType: selections.sleeveType || "Standard",
    neckType: selections.neckType || "Round",
    length: selections.length || "Regular",
    pattern: selections.pattern || "Plain",
    embroidery: selections.embroidery || "None",
    threadWork: selections.threadWork || "None",
    stoneWork: selections.stoneWork || "None",
    description: dynamicDesc,
    cloudinaryPath: `StyleMate/custom-design/final/${targetType.toLowerCase()}/custom-design.png`,
  };
}
